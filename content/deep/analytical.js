<ul>
<li><b>Solution pressure</b>: the tendency of the <b>metal to dissolve</b> into solution as ions.</li>
<li><b>Ionic pressure</b>: the tendency of the <b>metal ions to deposit</b> on the rod as metal.</li>
</ul>
