<p>تحويل جزيئات كبيرة لصغيرة محتاج شغل (كهربي، ميكانيكي، موجات). النتيجة مساحة سطحية ضخمة بـ<b>طاقة سطحية حرة عالية</b>. وده <b>نظام غير مستقر ديناميكيًا حراريًا</b>: الجزيئات "عايزة" تتجمع تاني عشان تقلل المساحة والطاقة. والتكتل ده اسمه <b>aggregation</b>.</p>
